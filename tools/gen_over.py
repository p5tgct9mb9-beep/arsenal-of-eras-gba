def inpoly(x,y,P):
    c=False;n=len(P)
    for i in range(n):
        x1,y1=P[i];x2,y2=P[(i+1)%n]
        if (y1>y)!=(y2>y) and x<(x2-x1)*(y-y1)/(y2-y1)+x1:c=not c
    return c
def build_masks():
    if os.path.exists(CACHE):
        b=open(CACHE,'rb').read();return [b[i*MW*MH:(i+1)*MW*MH] for i in range(2)]
    from global_land_mask import globe
    out=[]
    for nm,l0,l1,b0,b1 in TH:
        m=bytearray(MW*MH)
        for y in range(MH):
            lat=b1-(y+.5)*(b1-b0)/MH
            for x in range(MW):
                lon=l0+(x+.5)*(l1-l0)/MW
                m[y*MW+x]=1 if globe.is_land(lat,lon if lon<=180 else lon-360) else 0
        out.append(bytes(m))
    open(CACHE,'wb').write(b''.join(out));return out
PAL=[(14,34,72),(24,56,104),(66,104,58),(92,124,70),(150,140,96),(196,206,214),(122,72,62),(140,96,74),(176,170,180),(40,40,40),(240,240,240),(170,40,40),(230,200,90),(90,160,230),(255,255,255),(0,0,0)]
# 0 deep sea 1 shallow 2 west lowland 3 west upland 4 desert 5 ice/tundra 6 bloc lowland 7 bloc steppe 8 bloc tundra ...
def rgb(r,g,b):return (r>>3)|((g>>3)<<5)|((b>>3)<<10)
def gen():
    masks=build_masks();OUT=["// generated by tools/gen_over.py - OVERFLIGHT theatre maps (4bpp, 240x144) + palette"]
    OUT.append("static const unsigned short ov_pal[16]={%s};"%",".join(str(rgb(*c)) for c in PAL))
    imgs=[]
    for t,(nm,l0,l1,b0,b1) in enumerate(TH):
        m=masks[t];px=[0]*(MW*MH)
        for y in range(MH):
            lat=b1-(y+.5)*(b1-b0)/MH
            for x in range(MW):
                lon=l0+(x+.5)*(l1-l0)/MW
                if not m[y*MW+x]:
                    near=any(0<=x+dx<MW and 0<=y+dy<MH and m[(y+dy)*MW+x+dx] for dx in(-2,0,2) for dy in(-2,0,2))
                    px[y*MW+x]=1 if near else 0;continue
                bloc=inpoly(lon,lat,BLOC)
                nz=math.sin(lon*0.83)+math.sin(lat*1.31+lon*0.47)+0.6*math.sin(lon*2.1-lat*1.7)
                desert=(36+nz<lat<47+nz*0.8 and 50+nz*2<lon<80+nz*2) or (38+nz<lat<46+nz and 90+nz*3<lon<112+nz*2)
                tundra=lat>65+nz*1.2
                if bloc:c=8 if tundra else 7 if desert else 6
                else:c=5 if tundra else 4 if desert else (3 if ((x*7+y*13)%11)<3 else 2)
                px[y*MW+x]=c
        imgs.append(px)
        b=[px[i]|(px[i+1]<<4) for i in range(0,len(px),2)]
        OUT.append("static const unsigned char ov_map%d[%d]={"%(t,len(b)));
        for i in range(0,len(b),48):OUT.append(",".join(str(v) for v in b[i:i+48])+",")
        OUT.append("};")
        OUT.append("#define OV%d_L0 %d\n#define OV%d_L1 %d\n#define OV%d_B0 %d\n#define OV%d_B1 %d"%(t,int(l0*10),t,int(l1*10),t,int(b0*10),t,int(b1*10)))
    # aircraft top-down sprites 15x15 (index art, 0 clear) : U-2 (long glider wings), SR-71 (chined delta), MiG, tanker
    S={"u2":["       a       ","       a       ","       a       ","      aaa      ","aaaaaaaaaaaaaaa","bbbbbbbaabbbbbb","       a       ","       a       ","       a       ","       a       ","      aaa      ","     aaaaa     ","               ","               ","               "],
       "sr":["       a       ","       a       ","      aaa      ","      aaa      ","     aabaa     ","     aabaa     ","    aaabaaa    ","   aaaabaaaa   ","  aaaaabaaaaa  "," aaaaaaaaaaaaa ","aaaaaaaaaaaaaaa","  aa   a   aa  ","  a         a  ","               ","               "],
       "mig":["       a       ","       a       ","      aaa      ","      aaa      ","     aaaaa     ","    aaaaaaa    ","   aaaaaaaaa   ","  aaaaaaaaaaa  ","       a       ","     aaaaa     ","               ","               ","               ","               ","               "],
       "kc":["       a       ","       a       ","       a       ","  aaaaaaaaaaa  ","aaaaaaaaaaaaaaa","     a a a     ","       a       ","       a       ","       a       ","     aaaaa     ","       b       ","       b       ","               ","               ","               "]}
    for k,v in S.items():
        bits=[]
        for row in v:
            bits+=[(1 if ch=='a' else 2 if ch=='b' else 0) for ch in row.ljust(15)]
        OUT.append("static const unsigned char ov_spr_%s[225]={%s};"%(k,",".join(map(str,bits))))
    open(os.path.join(ROOT,'src','overdb.inc'),'w').write("\n".join(OUT)+"\n")
    try:
        from PIL import Image
        for t,px in enumerate(imgs):
            im=Image.new('RGB',(MW,MH));im.putdata([PAL[c] for c in px]);im.resize((MW*3,MH*3),Image.NEAREST).save('/tmp/ov/map%d.png'%t)
    except Exception:pass
gen()
