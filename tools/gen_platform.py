def outl(g,col=1):
    h=len(g);w=len(g[0]);o=[r[:] for r in g]
    for y in range(h):
        for x in range(w):
            if g[y][x]==0 and any(0<=x+dx<w and 0<=y+dy<h and g[y+dy][x+dx] not in (0,col) for dx,dy in((1,0),(-1,0),(0,1),(0,-1))):o[y][x]=col
    return o
def G(w,h):return [[0]*w for _ in range(h)]
def R(g,x0,y0,x1,y1,c):
    for y in range(max(0,y0),min(len(g),y1+1)):
        for x in range(max(0,x0),min(len(g[0]),x1+1)):g[y][x]=c
def E(g,x0,y0,x1,y1,c):
    cx=(x0+x1)/2;cy=(y0+y1)/2;rx=(x1-x0)/2+.5;ry=(y1-y0)/2+.5
    for y in range(max(0,y0),min(len(g),y1+1)):
        for x in range(max(0,x0),min(len(g[0]),x1+1)):
            if ((x-cx)/rx)**2+((y-cy)/ry)**2<=1.0:g[y][x]=c
def P(g,x,y,c):
    if 0<=y<len(g) and 0<=x<len(g[0]):g[y][x]=c
def L(g,x0,y0,x1,y1,c):
    n=max(abs(x1-x0),abs(y1-y0),1)
    for i in range(n+1):P(g,round(x0+(x1-x0)*i/n),round(y0+(y1-y0)*i/n),c)
def hflip(g):return [r[::-1] for r in g]
