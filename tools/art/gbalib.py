def tw(s,scale=1): return len(s)*6*scale-scale
def text(im,x,y,s,col=WHITE,shadow=SHADOW,scale=1,adv=6):
    px=im.load(); W,H=im.size
    for layer in ((1,shadow),(0,col)) if shadow else ((0,col),):
        off,c=layer
        cx=x
        for ch in s:
            g=GLYPH.get(ch.upper() if ch not in GLYPH else ch,GLYPH['?'])
            for r,row in enumerate(g):
                for cc,b in enumerate(row):
                    if b=='#':
                        for dy in range(scale):
                            for dx in range(scale):
                                X=cx+cc*scale+dx+off; Y=y+r*scale+dy+off
                                if 0<=X<W and 0<=Y<H: px[X,Y]=c
            cx+=adv*scale
def native(path):
    im=Image.open(path).convert('RGB')
    if im.size==(720,480): im=im.resize((240,160),Image.NEAREST)
    return im
def up(im,f=3): return im.resize((im.width*f,im.height*f),Image.NEAREST)
_set=None
def _slice():
    global _set
    if _set is None: _set=native(SHOTS+'/v12_settings_default.png')
    return _set
def panel(im,x0,y0,x1,y1,fill=NAVY):
    """9-slice gold panel copied from the real settings screen. x1,y1 inclusive."""
    s=_slice(); C=8
    d=ImageDraw.Draw(im)
    if fill: d.rectangle((x0+C,y0+C,x1-C,y1-C),fill=fill)
    tl=s.crop((4,4,12,12)); tr=s.crop((228,4,236,12)); bl=s.crop((4,148,12,156)); br=s.crop((228,148,236,156))
    top=s.crop((14,4,15,12)); bot=s.crop((14,148,15,156)); lef=s.crop((4,40,12,41)); rig=s.crop((228,40,236,41))
    for x in range(x0+C,x1-C+1):
        im.paste(top,(x,y0)); im.paste(bot,(x,y1-C+1))
    for y in range(y0+C,y1-C+1):
        im.paste(lef,(x0,y)); im.paste(rig,(x1-C+1,y))
    # fill the inner parts of edges with fill colour where slice was navy
    im.paste(tl,(x0,y0)); im.paste(tr,(x1-C+1,y0)); im.paste(bl,(x0,y1-C+1)); im.paste(br,(x1-C+1,y1-C+1))
    if fill and fill!=NAVY:
        px=im.load()
        for x in range(x0,x1+1):
            for y in range(y0,y1+1):
                if px[x,y]==NAVY: px[x,y]=fill
def mockup_tag(im,x=None,y=None):
    s='MOCKUP'; w=tw(s)+4
    if x is None: x=im.width-w-2
    if y is None: y=2
    d=ImageDraw.Draw(im)
    d.rectangle((x,y,x+w,y+10),fill=(8,8,8)); d.rectangle((x+1,y+1,x+w-1,y+9),fill=(214,33,57))
    text(im,x+2,y+2,s,WHITE,shadow=None)
