#!/usr/bin/env python3
"""mkarc.py - generate one harness script per Arcade Cabinet game (ds_arc_<g>.txt).
Each: open the cabinet, pick game g, play it by hand (all buttons incl. X/Y, no START) for ~25 s,
pause/resume, quit, let the score entry finish, play again + quit, then a full autopilot game
(up to the 4-minute cap) via the 0x4147000g jump code, then back to the cabinet and out to the menu.
The log beats (scr/mode/score/maxstall) and the shots are checked by tools/arccheck.py."""
import os, random
H = os.path.dirname(os.path.abspath(__file__))
NAV = ['wait 100', 'tap START', 'wait 30', 'tap RIGHT', 'wait 6', 'tap DOWN', 'wait 6', 'tap DOWN', 'wait 6', 'tap A', 'wait 30',
       'tap A', 'wait 40', 'shot hub', 'wait 10']
# no B/Y in the fuzz: on GAME OVER they mean 'back to cabinet' (tested explicitly below)
KEYS = ['A', 'X', 'L', 'R', 'UP', 'DOWN', 'LEFT', 'RIGHT', 'A+LEFT', 'A+RIGHT', 'A+UP', 'X+DOWN', 'X+UP', 'L+DOWN', 'R+UP']
for g in range(12):
    rnd = random.Random(1000 + g); s = list(NAV) + ['tap RIGHT', 'wait 8'] * g + ['wait 20', 'shot cab', 'beat cab', 'reset', 'tap A', 'wait 90', 'shot start', 'beat start', 'hold Y 3', 'ctlstat y', 'hold X 3', 'ctlstat x', 'wait 4']
    t = 0
    while t < 1500:
        k = rnd.choice(KEYS); n = rnd.randint(6, 40); s.append('hold %s %d' % (k, n)); t += n
        if t % 300 < 40: s += ['beat play']
    s += ['shot play', 'beat play', 'tap START', 'wait 20', 'shot pause', 'beat pause', 'tap A', 'wait 60', 'hold A 30', 'beat resumed',
          'tap START', 'wait 20', 'tap B', 'wait 30', 'shot over1', 'beat over1', 'poke32 0203FFD0 4F545541', 'wait 220', 'beat back1', 'poke32 0203FFD0 0', 'wait 90',
          # play again path: start, quit at once (score 0 -> no initials), A = play again, quit, B = cabinet
          'tap A', 'wait 60', 'tap START', 'wait 20', 'tap B', 'wait 40', 'shot over2', 'beat over2', 'tap A', 'wait 90', 'beat again', 'tap START', 'wait 20', 'tap B', 'wait 40',
          'beat over3', 'tap B', 'wait 60', 'shot cab2', 'beat cab2',
          # autopilot full game
          'poke32 0203FFD0 4F545541', 'poke32 0203FFD8 %08X' % (0x41470000 + g)]
    for i in range(16): s += ['wait 1000', 'beat auto']
    s += ['shot autoend', 'wait 400', 'beat auto_back', 'poke32 0203FFD0 0', 'wait 60', 'shot cab3', 'beat cab3', 'peek 0203FFD0 2',
          'tap B', 'wait 60', 'shot exit', 'beat exit', 'beat end']
    open(os.path.join(H, 'ds_arc_%02d.txt' % g), 'w').write('#newmenu\n# generated by mkarc.py: arcade cabinet game %d\n' % g + '\n'.join(s) + '\n')
print('wrote 12 arcade scripts')
