#!/usr/bin/env python3
"""mkctl.py - generate the DS button-layout harness scripts (ds_ctl_*.txt).
Each enters a mode with the normal menu path, then holds X, Y, L, R and records the translated
key mask (ctlstat: map = GBA bits the game saw, cat = control category) plus a screenshot."""
import os
H = os.path.dirname(os.path.abspath(__file__))
def lines(f, upto):
    out = []
    for l in open(os.path.join(H, f)):
        out.append(l.rstrip('\n'))
        if l.startswith('shot ' + upto): break
    return out
def probe(n, pre=()):
    p = list(pre) + ['ctlstat %s_pre' % n]
    for k in ('X', 'Y', 'L', 'R', 'B'):
        p += ['hold %s 3' % k, 'ctlstat %s_%s' % (n, k), 'hold %s 5' % k, 'shot %s_%s' % (n, k), 'wait 30']
    return p + ['ctlstat %s_end' % n, 'beat end']
naval = lines('ds_naval.txt', 'naval_start')
def retarget(src, downs):  # 6v6 category: DOWN x n picks infantry/armor/air/naval
    out = []; skipping = False; done = False
    for l in src:
        if not done and l == 'tap DOWN':
            if not skipping:
                skipping = True; out += ['tap DOWN', 'wait 6'] * downs
            continue
        if skipping and not done and l == 'wait 6': continue
        if skipping and not done: done = True
        out.append(l)
    return out
S = {
 'inf': lines('ds_inf_soldiers.txt', 'inf_start') + probe('inf', ['hold A 40']),
 'armor': lines('ds_armor.txt', 'ds_armor_start') + probe('armor'),
 'air': retarget(naval, 2) + probe('air'),
 'naval': naval + probe('naval'),
 'fps': [l for l in open(os.path.join(H, '..', '..', 'tools', 'v13_fps_0.txt')).read().split('\n') if l][:40] + probe('fps', ['wait 120']),
 'menu': ['wait 100', 'tap START', 'wait 30', 'shot menu_tiles'] + probe('menu')[:-1],
 'settings': ['wait 100', 'tap START', 'wait 30', 'tap RIGHT', 'wait 6'] + ['tap DOWN', 'wait 6'] * 4 + ['tap A', 'wait 30', 'shot extras',
         'tap DOWN', 'wait 6', 'tap DOWN', 'wait 6', 'tap A', 'wait 30', 'shot settings_hub', 'tap A', 'wait 30', 'shot settings_open']
         + ['tap DOWN', 'wait 4'] * 7 + ['shot settings_controls_ds', 'tap A', 'wait 10', 'shot settings_controls_classic', 'ctlstat classic',
            'hold X 3', 'ctlstat classic_X', 'hold Y 3', 'ctlstat classic_Y', 'tap A', 'wait 10', 'shot settings_controls_ds2', 'tap A', 'wait 10', 'tap B', 'wait 30', 'sram64 FFC0', 'beat end'],
}
for k, v in S.items():
    open(os.path.join(H, 'ds_ctl_%s.txt' % k), 'w').write('#newmenu\n# generated by mkctl.py: DS button layout probe (%s)\n' % k + '\n'.join(v) + '\n')
print('wrote', ', '.join('ds_ctl_%s.txt' % k for k in S))
