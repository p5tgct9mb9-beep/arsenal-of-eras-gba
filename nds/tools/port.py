#!/usr/bin/env python3
"""port.py - generate the DS build of the shared GBA source.

Copies ../src/*.inc + main.c into nds/gen/, rewrites the handful of hard-coded GBA hardware
addresses to the compat-layer macros in nds/source/gba_ds.h, and splits src/assets.c:
small arrays stay in RAM (gen/assets_ds.c), big ones (>= BIG bytes) go to NitroFS
(nitrofiles/assets.bin) and are paged in on first use by ast_load() (LRU cache).
Run from nds/:  python3 tools/port.py
"""
import os, re, sys, struct, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
NDS = os.path.dirname(HERE); ROOT = os.path.dirname(NDS); SRC = os.path.join(ROOT, 'src')
GEN = os.path.join(NDS, 'gen'); NFS = os.path.join(NDS, 'nitrofiles')
BIG = int(os.environ.get('AOE_BIG', 16384))
os.makedirs(GEN, exist_ok=True); os.makedirs(NFS, exist_ok=True)

TSZ = {'unsigned char': 1, 'signed char': 1, 'char': 1, 'unsigned short': 2, 'short': 2, 'signed short': 2,
       'unsigned int': 4, 'int': 4, 'signed int': 4, 'u8': 1, 's8': 1, 'u16': 2, 's16': 2, 'u32': 4, 's32': 4}
TFMT = {1: 'B', 2: 'H', 4: 'I'}

# ---------------------------------------------------------------- assets split
hdr = open(os.path.join(SRC, 'assets.h')).read().splitlines()
decl = {}  # name -> (type, count)
for l in hdr:
    m = re.match(r'extern const (.+?) (\w+)\[(\d+)\];', l)
    if m: decl[m.group(2)] = (m.group(1), int(m.group(3)))
moved = {}; keep_lines = []; blob = bytearray(); index = []
# assets that must stay in RAM (used in static initializers or by address in tight code); grown as needed
KEEP = set(open(os.path.join(HERE, 'keep_assets.txt')).read().split()) if os.path.exists(os.path.join(HERE, 'keep_assets.txt')) else set()
for l in open(os.path.join(SRC, 'assets.c')):
    m = re.match(r'const (.+?) (\w+)\[(\d+)\]( __attribute__\(\(aligned\(4\)\)\))?=\{(.*)\};\s*$', l)
    if not m:
        if l.startswith('#include'): keep_lines.append('#include "assets_ds.h"\n')
        else: keep_lines.append(l)
        continue
    t, name, n = m.group(1), m.group(2), int(m.group(3))
    if t not in TSZ:
        keep_lines.append(l); continue
    sz = TSZ[t] * n
    if sz < BIG or name in KEEP:
        keep_lines.append(l); continue
    vals = [int(v, 0) for v in m.group(5).split(',') if v.strip()]
    vals += [0] * (n - len(vals))
    fmt = TFMT[TSZ[t]]; signed = not t.startswith('unsigned') and t not in ('u8', 'u16', 'u32')
    if signed: fmt = fmt.lower()
    while len(blob) % 4: blob.append(0)
    off = len(blob); blob += struct.pack('<%d%s' % (n, fmt), *vals)
    moved[name] = (t, n, len(index)); index.append((off, sz, name))
open(os.path.join(NFS, 'assets.bin'), 'wb').write(blob)
with open(os.path.join(GEN, 'assets_ds.h'), 'w') as f:
    f.write('// generated by nds/tools/port.py - do not edit\n#pragma once\n')
    f.write('#define AST_N %d\nextern const void* ast_ptr[AST_N];\nconst void* ast_load(int id);\n' % len(index))
    f.write('#define AST(id) (ast_ptr[id]?ast_ptr[id]:ast_load(id))\n')
    for l in hdr:
        m = re.match(r'extern const (.+?) (\w+)\[(\d+)\];', l)
        if m and m.group(2) in moved:
            name = m.group(2); f.write('#define %s ((const %s*)AST(%d))\n' % (name, moved[name][0], moved[name][2]))
        elif l.strip() != '#pragma once': f.write(l + '\n')
with open(os.path.join(GEN, 'assets_ds.c'), 'w') as f:
    f.write(''.join(keep_lines))
    f.write('\nconst unsigned int ast_index[%d][2]={%s};\n' % (max(1, len(index)), ','.join('{%d,%d}' % (o, s) for o, s, _ in index) or '{0,0}'))
    f.write('const char*const ast_names[%d]={%s};\n' % (max(1, len(index)), ','.join('"%s"' % nm for _, _, nm in index) or '""'))
    f.write('const unsigned int ast_blob_crc=0x%s;\n' % hashlib.md5(blob).hexdigest()[:8])

# ---------------------------------------------------------------- source rewrite
def sub_sizeof(s):
    for name, (t, n, _) in moved.items():
        if name not in s: continue
        s = re.sub(r'sizeof\s*\(\s*%s\s*\)' % name, '(%d*sizeof(%s))' % (n, t), s)
        s = re.sub(r'sizeof\s+%s\b' % name, '(%d*sizeof(%s))' % (n, t), s)
    return s

FUNC_REPL = {
 # core.inc
 r'void \*memcpy\(void \*d,const void \*s,unsigned n\)\{[^\n]*\n': '',
 r'void \*memset\(void \*d,int v,unsigned n\)\{[^\n]*\n': '',
 r'#define EWRAM __attribute__\(\(section\("\.ewram"\)\)\)': '#define EWRAM',
 r'static void vsync\(void\)\{[^\n]*\}': 'static void vsync(void){gba_vsync();}',
 r'static void dma32\(const void\*src,volatile void\*dst,u32 words\)\{[^\n]*\}':
   'static void dma32(const void*src,volatile void*dst,u32 words){const u32*s=(const u32*)src;volatile u32*d=(volatile u32*)dst;while(words--)*d++=*s++;}',
 r'static void fill32\(volatile void\*dst,u32 val,u32 words\)\{[^\n]*\n':
   'static void fill32(volatile void*dst,u32 val,u32 words){volatile u32*d=(volatile u32*)dst;while(words--)*d++=val;}\n',
 # sniper.inc / kc.inc DMA helpers (16-bit copies)
 r'static void sn_movr\(const void\*src,void\*dst,int n\)\{[^\n]*\}':
   'static void sn_movr(const void*src,void*dst,int n){if(n<=0)return;const volatile u16*s=(const u16*)src+n-1;volatile u16*d=(u16*)dst+n-1;while(n--)*d--=*s--;}',
 r'static void dma16c\(const void\*src,void\*dst,int n\)\{[^\n]*\}':
   'static void dma16c(const void*src,void*dst,int n){if(n<=0)return;const volatile u16*s=(const u16*)src;volatile u16*d=(u16*)dst;while(n--)*d++=*s++;}',
 r'static void krow_copy\(u16\*d,const u16\*s,int n\)\{[^\n]*\}':
   'static void krow_copy(u16*d,const u16*s,int n){volatile u16*D=d;const volatile u16*S=s;while(n-->0)*D++=*S++;}',
 r'__attribute__\(\(section\("\.ewram"\)\)\)': '',
 r'\bint main\(void\)': 'int gba_main(void)',
 # GBA EWRAM overflow past the 240x160 back buffers was harmless there; give them guard rows on DS
 r'static u16 fb\[240\*160\] EWRAM;': 'static u16 fb[240*160+240*16] EWRAM;',
 r'static u16 bigbuf\[240\*160\] EWRAM;': 'static u16 bigbuf[240*160+240*16] EWRAM;',
}
NO_VRAM_REWRITE = {'braddb.inc'}
def rewrite(fn, s):
    for pat, rep in FUNC_REPL.items(): s = re.sub(pat, lambda m: rep, s)
    s = s.replace('#include "gba.h"', '#include "gba_ds.h"').replace('#include "assets.h"', '#include "assets_ds.h"')
    s = re.sub(r'0x0203[Ff][Ff]([0-9A-Fa-f]{2})\b', r'(GBA_BEATBASE+0x\1)', s)
    s = re.sub(r'0x0?[Ee]000000\b', 'GBA_SRAM_ADDR', s)
    s = re.sub(r'0x0?3007[Ff][Ff][Cc]\b', 'GBA_DUMMY_ADDR', s)
    s = re.sub(r'0x0?3007[Ff][Ff]8\b', '(GBA_DUMMY_ADDR+4)', s)
    s = re.sub(r'0x0?7000000\b', 'GBA_OAM_ADDR', s)
    s = re.sub(r'0x0?601([0-9A-Fa-f]{4})\b', r'0x0640\1', s)
    if fn not in NO_VRAM_REWRITE:
        s = re.sub(r'0x0?600([0-9A-Fa-f]{4})\b', r'(GBA_BMP_ADDR+0x\1)', s)
    # literal I/O pointers: (volatile T*)0x40000xx -> shadow
    s = re.sub(r'(\*\s*\)\s*)0x0?(400[0-3][0-9A-Fa-f]{3})\b', r'\1GBA_IO(0x\2)', s)
    s = sub_sizeof(s)
    # static pointer tables whose entries are NitroFS assets -> switch functions (lazy loading)
    def tab(m):
        typ, nm, body = m.group(1), m.group(2), m.group(4)
        names = [x.strip() for x in body.split(',') if x.strip()]
        if not names or not all(x in moved for x in names): return m.group(0)
        TABS.add(nm)
        cases = ''.join('case %d:return %s;' % (i, x) for i, x in enumerate(names))
        return 'static %s*%s_f(int i){switch(i){%sdefault:return %s;}}' % (typ, nm, cases, names[0])
    s = re.sub(r'static (const \w+)\*const (\w+)\[(\w*)\]=\{([^}]*)\};', tab, s)
    for nm in TABS:
        s = re.sub(r'\b%s\[' % nm, '%s_f(' % nm, s)
    return s
TABS = set()
def fix_brackets(s):
    # turn NAME_f(expr] into NAME_f(expr) (bracket matching)
    for nm in TABS:
        out = []; i = 0; key = nm + '_f('
        while True:
            j = s.find(key, i)
            if j < 0: out.append(s[i:]); break
            out.append(s[i:j + len(key)]); k = j + len(key); depth = 0
            while k < len(s):
                c = s[k]
                if c in '([': depth += 1
                elif c in ')]':
                    if depth == 0:
                        if c == ']': c = ')'
                        out.append(c); k += 1; break
                    depth -= 1
                out.append(c); k += 1
            i = k
        s = ''.join(out)
    return s

files = sorted(f for f in os.listdir(SRC) if f.endswith('.inc')) + ['main.c']
for fn in files: rewrite(fn, open(os.path.join(SRC, fn), encoding='latin-1').read())  # pass 1: collect TABS
changed = 0
for fn in files:
    s = open(os.path.join(SRC, fn), encoding='latin-1').read()
    o = fix_brackets(rewrite(fn, s))
    if fn == 'main.c': o += '\n#include "ds_hooks.inc"\n'
    out = os.path.join(GEN, 'game.c' if fn == 'main.c' else fn)
    if not os.path.exists(out) or open(out, encoding='latin-1').read() != o:
        open(out, 'w', encoding='latin-1').write(o); changed += 1
print('port.py: %d files (%d changed), %d assets kept in RAM, %d moved to NitroFS (%d KB)' % (
    len(files), changed, len(decl) - len(moved), len(moved), len(blob) // 1024))
