files = sorted(set(f for d in (SRC, OVL) if os.path.isdir(d) for f in os.listdir(d) if f.endswith('.inc'))) + ['main.c']
for fn in files: rewrite(fn, srcread(fn))  # pass 1: collect TABS
changed = 0
for fn in files:
    s = srcread(fn)
    o = fix_brackets(rewrite(fn, s))
    if fn == 'main.c': o += '\n#include "ds_hooks.inc"\n'
    out = os.path.join(GEN, 'game.c' if fn == 'main.c' else fn)
    if not os.path.exists(out) or open(out, encoding='latin-1').read() != o:
        open(out, 'w', encoding='latin-1').write(o); changed += 1
