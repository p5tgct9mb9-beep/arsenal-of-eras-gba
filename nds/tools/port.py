NO_VRAM_REWRITE = {'braddb.inc'}
DSVER = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'VERSION')).read().strip()
def rewrite(fn, s):
    # edition / version strings (the GBA source says FIELD EDITION V1.3.5)
    ed = 'DS EDITION V' + DSVER
    s = s.replace('m3_text(120-(20*6)/2,22,"FIELD EDITION V1.3.5"', 'm3_text(120-(%d*6)/2,22,"%s"' % (len(ed), ed))
    s = s.replace('"FIELD EDITION V1.3.5"', '"%s"' % ed).replace('"A GBA FIELD EDITION - BY LT VASQUEZ"', '"A DS FIELD EDITION - BY LT VASQUEZ"')
    for pat, rep in FUNC_REPL.items(): s = re.sub(pat, lambda m: rep, s)
    s = s.replace('#include "gba.h"', '#include "gba_ds.h"').replace('#include "assets.h"', '#include "assets_ds.h"')
    s = re.sub(r'0x0203[Ff][Ff]([0-9A-Fa-f]{2})\b', r'(GBA_BEATBASE+0x\1)', s)
    s = re.sub(r'0x0?[Ee]000000\b', 'GBA_SRAM_ADDR', s)
    s = re.sub(r'0x0?3007[Ff][Ff][Cc]\b', 'GBA_DUMMY_ADDR', s)
    s = re.sub(r'0x0?3007[Ff][Ff]8\b', '(GBA_DUMMY_ADDR+4)', s)
    s = re.sub(r'0x0?7000000\b', 'GBA_OAM_ADDR', s)
    s = re.sub(r'0x0?601([0-9A-Fa-f]{4})\b', r'0x0640\1', s)
    if fn not in NO_VRAM_REWRITE:
        s = re.sub(r'0x0?600([0-9A-Fa-f]{4})\b', r'(GBA_BMP_ADDR+0x\1)', s)
    # literal I/O pointers: (volatile T*)0x40000xx -> shadow
    s = re.sub(r'(\*\s*\)\s*)0x0?(400[0-3][0-9A-Fa-f]{3})\b', r'\1GBA_IO(0x\2)', s)
    s = sub_sizeof(s)
    # static pointer tables whose entries are NitroFS assets -> switch functions (lazy loading)
    def tab(m):
        typ, nm, body = m.group(1), m.group(2), m.group(4)
        names = [x.strip() for x in body.split(',') if x.strip()]
        if not names or not all(x in moved for x in names): return m.group(0)
        TABS.add(nm)
        cases = ''.join('case %d:return %s;' % (i, x) for i, x in enumerate(names))
        return 'static %s*%s_f(int i){switch(i){%sdefault:return %s;}}' % (typ, nm, cases, names[0])
    s = re.sub(r'static (const \w+)\*const (\w+)\[(\w*)\]=\{([^}]*)\};', tab, s)
    for nm in TABS:
        s = re.sub(r'\b%s\[' % nm, '%s_f(' % nm, s)
    return s
TABS = set()
def fix_brackets(s):
    # turn NAME_f(expr] into NAME_f(expr) (bracket matching)
    for nm in TABS:
        out = []; i = 0; key = nm + '_f('
        while True:
            j = s.find(key, i)
            if j < 0: out.append(s[i:]); break
            out.append(s[i:j + len(key)]); k = j + len(key); depth = 0
            while k < len(s):
                c = s[k]
                if c in '([': depth += 1
                elif c in ')]':
                    if depth == 0:
                        if c == ']': c = ')'
                        out.append(c); k += 1; break
                    depth -= 1
                out.append(c); k += 1
            i = k
        s = ''.join(out)
    return s

# DS overlay: newer versions of GBA source files (e.g. the unreleased v1.3.6 soldier sprites from gba-wip 5efcaac)
OVL = os.path.join(NDS, 'overlay')
def srcpath(fn): o = os.path.join(OVL, fn); return o if os.path.exists(o) else os.path.join(SRC, fn)
def srcread(fn):
    if fn in ovl_rewrite: return ovl_rewrite[fn]
    t = open(srcpath(fn), encoding='latin-1').read()
    # stream one soldier set (a few KB) instead of loading the whole 580 KB table into the heap
    t = t.replace('sd_rle+sd_off[set]', 'ast_window(sd_rle_ID,sd_off[set],sd_off[set+1]-sd_off[set])')
    for a, b in LIT_REPL:
        if a in t: t = t.replace(a, b)
    return t
